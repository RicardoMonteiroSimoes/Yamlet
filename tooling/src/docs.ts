// `yamlet docs` — render specs and decision records as Markdown for people.
//
// The YAML is the source of truth and stays the only thing anyone edits. This
// command projects it into a tree of Markdown pages meant to be committed and
// read where the code lives (GitHub, GitLab, an IDE preview) by teammates and
// stakeholders who never run the CLI:
//
//   TARGET/index.md                  every system and its scopes, every decision, a map of
//                                    which composite holds which scope
//   TARGET/<system>/<scope>.md       one per spec: contract, members and wiring (composites),
//                                    requirements with each criterion as an EARS sentence,
//                                    the decisions that decide them, who uses the scope
//   TARGET/decisions/<…>/<adr>.md    one per decision record, every status — a rejected or
//                                    superseded record is history, rendered and marked as such
//
// Tech specs are deliberately not rendered: they are disposable plans, and a
// committed rendering would outlive the plan it shows. Progress is `yamlet trace`.
//
// Because the output is committed, it can go stale. `--check` regenerates in
// memory and compares with TARGET without writing: exit 1 names every page that
// is missing, changed or no longer produced — the CI gate that keeps the pages
// honest. Every page opens with a "generated, do not edit" comment and links its
// source file, so a reader always knows where the truth lives.
//
// TARGET is a yamlet-owned directory, as for `yamlet tests`: every run wipes it
// and rebuilds, so a renamed or deleted spec never leaves an orphan page. Unlike a
// feature tree, a docs directory is a plausible place for hand-written files, so
// the wipe is guarded: a non-empty TARGET whose index.md was not written by this
// command is refused, and so is a TARGET that contains SRC.
//
// Parse, never validate: a file that does not parse is skipped and listed; a link
// that resolves to nothing renders as plain text. `yamlet verify` stays the judge.
//
// Exit codes: 0 ok (or up to date) · 1 --check found drift · 2 usage/path/collision/write error.

import type { CmdResult, Command, FlatRecord } from "./types.ts";
import { flatten } from "./flatten.ts";
