interface Skipped {
  file: string;
  reason: string;
}

/** Build every page in memory: path inside TARGET → content. */
function buildSite(
  src: string,
  targetAbs: string,
): { pages: Map<string, string>; skipped: Skipped[] } | string {
  const skipped: Skipped[] = [];
  const srcAbs = absPath(src);
  // Keys are paths relative to SRC, so the pages never depend on how SRC was spelled.
  const keyOf = (f: string): string => relative(srcAbs, absPath(f));
  const site: Site = {
    srcAbs,
    targetAbs,
    specs: new Map(),
    adrs: new Map(),
    usedBy: new Map(),
    linkedFrom: new Map(),
  };

  const claimed = new Map<string, string>();
  const claim = (page: string, key: string): string | null => {
    const prior = claimed.get(page);
    if (prior !== undefined) {
      return `two files map to the same page ${page}:\n  ${prior}\n  ${key}\n` +
        "rename one so their basenames differ";
    }
    claimed.set(page, key);
    return null;
  };
  claimed.set("index.md", "(the index)");

  for (const f of listSpecs(src)) {
    let text: string;
    try {
      text = Deno.readTextFileSync(f);
    } catch {
      skipped.push({ file: f, reason: "unreadable" });
      continue;
    }
    const { records, parseErrors } = flatten(text);
    if (parseErrors.length > 0) {
      skipped.push({ file: f, reason: "parse error (run `yamlet verify`)" });
      continue;
    }
    const key = keyOf(f);
    const doc = parseSpec(key, records);
    if (doc.system === "") {
      skipped.push({ file: f, reason: "no system" });
      continue;
    }
    const page = `${doc.system}/${baseOf(key).replace(/\.yamlet\.yaml$/, "")}.md`;
    const clash = claim(page, f);
    if (clash) return clash;
    site.specs.set(key, { page, doc });
  }

  for (const f of listFiles(src, ".adr.yaml")) {
    const loaded = loadAdr(f);
    if (!loaded) {
      skipped.push({ file: f, reason: "parse error (run `yamlet verify`)" });
      continue;
    }
    const key = keyOf(f);
    const page = `decisions/${key.replace(/\.adr\.yaml$/, "")}.md`;
    const clash = claim(page, f);
    if (clash) return clash;
    site.adrs.set(key, { key, page, adr: loaded.adr });
  }

  // Inverse indexes: the format holds none on purpose; a derived page may.
  for (const { doc } of site.specs.values()) {
    const dir = dirOf(doc.key);
    for (const m of doc.members) {
      const k = joinNorm(dir, m.path);
      site.usedBy.set(k, [...(site.usedBy.get(k) ?? []), { composite: doc.key, alias: m.alias }]);
    }
    const link = (adrs: string[], id: string) => {
      for (const a of adrs) {
        const k = joinNorm(dir, a);
        site.linkedFrom.set(k, [...(site.linkedFrom.get(k) ?? []), { spec: doc.key, id }]);
      }
    };
    for (const rq of doc.requirements) {
      link(rq.adrs, rq.id);
      for (const ac of rq.criteria) link(ac.adrs, ac.id);
    }
  }

  const pages = new Map<string, string>();
  const title = baseOf(srcAbs) || src;
  pages.set("index.md", renderIndex(site, title));
  for (const sp of site.specs.values()) pages.set(sp.page, renderSpec(site, sp));
  for (const ap of site.adrs.values()) pages.set(ap.page, renderAdr(site, ap));
  return { pages, skipped };
}

/** Every file under `dir`, as paths relative to it (dotfiles included — they are ours too). */
function treeOf(dir: string, rel = "", acc: string[] = []): string[] {
  let entries: Deno.DirEntry[];
  try {
    entries = [...Deno.readDirSync(rel === "" ? dir : `${dir}/${rel}`)];
  } catch {
    return acc;
  }
  for (const e of entries) {
    const p = rel === "" ? e.name : `${rel}/${e.name}`;
    if (e.isDirectory) treeOf(dir, p, acc);
    else acc.push(p);
  }
  return acc.sort();
}

function readOr(p: string): string | null {
  try {
    return Deno.readTextFileSync(p);
  } catch {
    return null;
  }
}

export function runDocs(args: string[]): CmdResult {
  let check = false;
  const positionals: string[] = [];
  for (const a of args) {
    if (a === "--check") check = true;
    else if (a.startsWith("-")) return die(`unknown flag for docs: ${a}`);
    else positionals.push(a);
  }
  if (positionals.length < 2) {
    return die("docs requires a source directory and a target directory: yamlet docs SRC TARGET");
  }
  if (positionals.length > 2) return die(`too many arguments: ${positionals[2]}`);
  const src = positionals[0]!;
  const target = positionals[1]!;

  try {
    if (!Deno.statSync(src).isDirectory) return die(`not a directory: ${src}`);
  } catch {
    return die(`source directory not found: ${src}`);
  }
  let targetExists = false;
  try {
    if (!Deno.statSync(target).isDirectory) {
      return die(`target exists but is not a directory: ${target}`);
    }
    targetExists = true;
  } catch {
    // Created below.
  }
  const srcAbs = absPath(src);
  const targetAbs = absPath(target);
  if (srcAbs === targetAbs || srcAbs.startsWith(targetAbs + "/")) {
    return die(`TARGET ${target} contains SRC ${src}: a run would erase the specs`);
  }

  const built = buildSite(src, targetAbs);
  if (typeof built === "string") return die(built);
  const { pages, skipped } = built;
  const skippedText = skipped.length === 0 ? "" : `skipped ${plural(skipped.length, "file")}:\n` +
    skipped.map((s) => `  ${s.file} — ${s.reason}\n`).join("");

  if (check) {
    const drift: string[] = [];
    const existing = new Set(targetExists ? treeOf(target) : []);
    for (const [p, content] of [...pages].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      const have = existing.has(p) ? readOr(`${target}/${p}`) : null;
      if (have === null) drift.push(`  missing  ${target}/${p}`);
      else if (have !== content) drift.push(`  changed  ${target}/${p}`);
    }
    for (const p of existing) if (!pages.has(p)) drift.push(`  extra    ${target}/${p}`);
    if (drift.length === 0) {
      return {
        exitCode: 0,
        stdout: `${target} is up to date (${plural(pages.size, "page")})\n` + skippedText,
        stderr: "",
      };
    }
    return {
      exitCode: 1,
      stdout: skippedText,
      stderr: `${target} is out of date with ${src}:\n${drift.join("\n")}\n` +
        `regenerate with: yamlet docs ${src} ${target}\n`,
    };
  }

  // TARGET is ours — but only once it has proved it: never wipe a directory of someone's own docs.
  if (targetExists && treeOf(target).length > 0) {
    const index = readOr(`${target}/index.md`);
    if (index === null || !index.startsWith(MARKER)) {
      return die(
        `${target} is not empty and was not written by \`yamlet docs\` (no generated index.md); ` +
          "refusing to erase it — pick an empty or new directory",
      );
    }
  }
  try {
    for (const e of targetExists ? [...Deno.readDirSync(target)] : []) {
      Deno.removeSync(`${target}/${e.name}`, { recursive: true });
    }
    for (const [p, content] of pages) {
      const dir = dirOf(p);
      Deno.mkdirSync(dir === "" ? target : `${target}/${dir}`, { recursive: true });
      Deno.writeTextFileSync(`${target}/${p}`, content);
    }
  } catch (e) {
    return die(`could not write ${target}: ${e instanceof Error ? e.message : String(e)}`);
  }

  const specs = [...pages.keys()].filter((p) => p !== "index.md" && !p.startsWith("decisions/"));
  const adrs = pages.size - 1 - specs.length;
  const stdout = `wrote ${plural(pages.size, "page")} to ${target} ` +
    `(${plural(specs.length, "scope")}, ${plural(adrs, "decision")}, index.md)\n` + skippedText;
  return { exitCode: 0, stdout, stderr: "" };
}

